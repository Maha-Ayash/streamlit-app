# Reflexion:
# Streamlit würde ich für schnelle Datenanalyse-Dashboards oder Prototypen wählen. 
# z.B. um CSV-Daten interaktiv zu filtern und zu visualisieren.
# Django oder FastAPI würde ich für produktive Webanwendungen oder APIs nutzen.
# z.B. ein Login-System mit Datenbank und Benutzerverwaltung (Django) oder eine schnelle REST-API für ein Backend (FastAPI).
# Grund: Streamlit ist ideal für einfache, schnelle UI ohne viel Backend-Setup, während Django/FastAPI für skalierbare, robuste Anwendungen gedacht sind.